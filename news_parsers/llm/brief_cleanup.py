"""Пост-обработка готового брифа: смысловое сжатие дублей и шума."""

from __future__ import annotations

from typing import Callable

from .config import BRIEF_MODEL, MAX_TOKENS
from .openrouter import chat_completion

DEFAULT_CLEANUP_SYSTEM_PROMPT = """Ты — жёсткий редактор аналитических брифов для руководства «Северстали».

Твоя главная задача: убрать глупые повторы и сжать однотипные новости ПО СМЫСЛУ.
Документ не переписывай с нуля: сохрани структуру, заголовки и порядок разделов, но сильно почисти содержимое.

ГЛАВНАЯ ПРОБЛЕМА, КОТОРУЮ НУЖНО ЛЕЧИТЬ:
В одном подпункте часто бывает 8–15 буллитов про одно и то же событие
(например, рост Brent/Urals: «выше $105», «почти $107», «достигла $107», «выросла более чем на 5%»).
Это НЕ разные новости. Это один сюжет. Его нужно схлопнуть в 1–3 сильных буллита.

ЖЁСТКИЕ ПРАВИЛА СЖАТИЯ:
1. Один сюжет / одна ценовая история / одно событие = один буллит (максимум два, если есть реально разные аспекты).
2. Почти-дубли схлопывай даже если цифры чуть отличаются ($105 и $107, «выросла» и «почти достигла», «из-за конфликта» и «из-за напряжённости»).
3. Внутри подпункта оставляй только уникальные смыслы. Если буллит не добавляет нового факта — удали.
4. Если в подпункте явно задан лимит (например 1–3 буллита) — соблюдай верхнюю границу.
5. Если лимит не указан, ориентир: 1–3 буллита на узкий подпункт; 3–5 только если факты реально разные.
6. Между разделами тоже не повторяй один и тот же сюжет дословно или почти дословно.
7. При схлопывании оставляй самую сильную версию: лучшие цифры, причина, география, следствие.
8. Можно слегка переформулировать буллит при склейке, но нельзя добавлять факты, которых не было в исходнике.
9. Не добавляй новые компании, страны, цифры, выводы и источники.
10. Не используй внешние знания.
11. Сохраняй формат: заголовки `##`, жирные подпункты, буллиты `-`.
12. Не удаляй важные уникальные цифры и конкретику, если они относятся к теме и ещё не отражены в оставленных буллитах.
13. Если после очистки в разделе не осталось смысла — оставь «Релевантных новостей нет» / «Релевантных новостей не выявлено.»
14. Ссылки [n] сохраняй только у фактов, которые остались; при склейке можно оставить несколько [n] у одного буллита.

ЧТО СЧИТАТЬ ДУБЛЕМ / ПОЧТИ-ДУБЛЕМ:
- одна и та же цена/инструмент с вариациями формулировки;
- одна причина события, повторённая разными словами;
- один дневной ход рынка, разбитый на много почти одинаковых пунктов;
- один факт, продублированный в соседних разделах.

ЧЕГО НЕЛЬЗЯ ДЕЛАТЬ:
- нельзя оставлять длинные «лесенки» повторов;
- нельзя придумывать пропущенные новости;
- нельзя менять тип брифа или ломать структуру разделов;
- нельзя писать комментарии редактора, список правок, JSON или служебные пометки.

Верни только итоговый очищенный текст брифа."""

CLEANUP_SYSTEM_PROMPT = DEFAULT_CLEANUP_SYSTEM_PROMPT

_BASE_SYSTEM_ROLE = (
    "Ты — редактор уже сгенерированного аналитического брифа. "
    "Верни только итоговый текст брифа без комментариев и служебных пометок."
)


def _cleanup_user_prompt(
    content: str,
    *,
    brief_kind: str,
    editor_instructions: str,
) -> str:
    instructions = (editor_instructions or "").strip() or CLEANUP_SYSTEM_PROMPT
    return (
        f"Тип брифа: {brief_kind}.\n\n"
        "=== ПРИОРИТЕТНЫЕ ИНСТРУКЦИИ РЕДАКТОРА (выполнять обязательно) ===\n"
        f"{instructions}\n"
        "=== КОНЕЦ ПРИОРИТЕТНЫХ ИНСТРУКЦИЙ ===\n\n"
        "Эти инструкции редактора имеют ВЫСШИЙ приоритет над остальными служебными "
        "подсказками. Если есть конфликт — выполняй инструкции редактора.\n\n"
        "Дополнительно (только если не противоречит инструкциям выше):\n"
        "• схлопни почти-дубли внутри подпунктов (особенно серии про одну цену/событие);\n"
        "• убери повторы между разделами;\n"
        "• соблюдай лимиты буллитов из структуры, если они есть;\n"
        "• не добавляй новые факты.\n\n"
        "Ниже уже сгенерированный бриф. Отредактируй его строго по приоритетным "
        "инструкциям редактора.\n\n"
        "=== НАЧАЛО БРИФА ===\n"
        f"{content.strip()}\n"
        "=== КОНЕЦ БРИФА ==="
    )


def cleanup_generated_brief(
    content: str,
    *,
    model: str | None = None,
    brief_kind: str = "full",
    system_prompt: str | None = None,
    should_cancel: Callable[[], bool] | None = None,
) -> tuple[str, bool]:
    source = (content or "").strip()
    if len(source) < 300:
        return source, False

    editor_instructions = (system_prompt or CLEANUP_SYSTEM_PROMPT).strip()
    cleaned = chat_completion(
        system_prompt=_BASE_SYSTEM_ROLE,
        user_prompt=_cleanup_user_prompt(
            source,
            brief_kind=brief_kind,
            editor_instructions=editor_instructions,
        ),
        model=model or BRIEF_MODEL,
        max_tokens=MAX_TOKENS,
        temperature=0.1,
        should_cancel=should_cancel,
    ).strip()

    if not cleaned or "=== НАЧАЛО БРИФА ===" in cleaned or cleaned.count("##") == 0:
        return source, False
    # Агрессивное сжатие дублей может сильно укоротить текст — порог ниже прежнего.
    if len(cleaned) < 300 or len(cleaned) < len(source) * 0.25:
        return source, False
    return cleaned, True
